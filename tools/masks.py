"""Rasterize the pinned source's Arial masks; generated data needs no font at build time.

Regeneration uses macOS Arial and a local Chromium canvas. CHROME may select
another Chromium binary. The font itself is never copied into the project.
"""
import html
import json
import os
from pathlib import Path
import re
import subprocess
import tempfile
ROOT = Path(__file__).resolve().parent.parent
SIZES = [127, 158, 176, 229]
source = (ROOT / 'reference/source.html').read_text()
mask_function = source[source.index('    function createMask('):source.index('    // ---------------------------------------------------------------------', source.index('    function createMask('))]
script = mask_function + """
const result = {};
for (const size of [127, 158, 176, 229]) {
  result[size] = [];
  for (let hour = 1; hour <= 12; hour++) {
    const mask = createMask(size, String(hour));
    const rows = [];
    for (let y = 0; y < size; y++) {
      const spans = [];
      let start = -1;
      for (let x = 0; x <= size; x++) {
        const inside = x < size && mask.data[(y * size + x) * 4] > 128;
        if (inside && start < 0) start = x;
        if (!inside && start >= 0) { spans.push(start, x); start = -1; }
      }
      rows.push(spans);
    }
    result[size].push(rows);
  }
}
document.body.textContent = JSON.stringify(result);
"""
candidates = sorted((Path.home() / 'Library/Caches/ms-playwright').glob('chromium_headless_shell-*/chrome-headless-shell-mac-arm64/chrome-headless-shell'))
chrome = os.environ.get('CHROME', str(candidates[-1]) if candidates else '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome')
with tempfile.TemporaryDirectory(prefix='ishihara-masks-') as temp:
    page = Path(temp) / 'masks.html'
    page.write_text('<!doctype html><body><script>' + script + '</script>')
    run = subprocess.run([chrome, '--headless', '--disable-gpu', '--no-first-run',
        '--no-default-browser-check', '--user-data-dir=' + temp + '/profile',
        '--dump-dom', page.as_uri()], capture_output=True, text=True, check=True, timeout=60)
    data = json.loads(html.unescape(re.search(r'<body>(.*?)</body>', run.stdout, re.S).group(1)))
output = ['// Copyright 2026 Luke Steuber. MIT License.',
    '// Generated by tools/masks.py from the pinned createMask(), using installed Arial.',
    '// Contains raster row spans only; no font software.', '#pragma once', '#include <stdint.h>']
for size in SIZES:
    cond = {127: 'defined(PBL_PLATFORM_BASALT) || defined(PBL_PLATFORM_DIORITE) || defined(PBL_PLATFORM_FLINT)',
            158: 'defined(PBL_PLATFORM_CHALK)', 176: 'defined(PBL_PLATFORM_EMERY)', 229: 'defined(PBL_PLATFORM_GABBRO)'}[size]
    output.append('#if !defined(PBL_DISPLAY_WIDTH) || ' + cond)
    offsets, spans = [], []
    for rows in data[str(size)]:
        for row in rows:
            offsets.append(len(spans))
            spans.extend(row)
        offsets.append(len(spans))
    for name, kind, values in [('OFFSETS', 'uint16_t', offsets), ('SPANS', 'uint8_t', spans)]:
        output.append(f'static const {kind} MASK_{size}_{name}[] = {{')
        for i in range(0, len(values), 32): output.append('  ' + ','.join(map(str, values[i:i+32])) + ',')
        output.append('};')
    output.append('#endif')
output.append('static bool hour_mask(int size, int hour, int x, int y) {')
output.append('  if (x < 0 || y < 0 || x >= size || y >= size) return false;')
output.append('  const uint16_t *offsets; const uint8_t *spans;')
output.append('  switch (size) {')
for size in SIZES:
    cond = {127: 'defined(PBL_PLATFORM_BASALT) || defined(PBL_PLATFORM_DIORITE) || defined(PBL_PLATFORM_FLINT)',
            158: 'defined(PBL_PLATFORM_CHALK)', 176: 'defined(PBL_PLATFORM_EMERY)', 229: 'defined(PBL_PLATFORM_GABBRO)'}[size]
    output += ['#if !defined(PBL_DISPLAY_WIDTH) || ' + cond,
        f'    case {size}: offsets = MASK_{size}_OFFSETS; spans = MASK_{size}_SPANS; break;', '#endif']
output += ['    default: return false;', '  }',
    '  int row = (hour - 1) * (size + 1) + y;',
    '  for (int i = offsets[row]; i < offsets[row + 1]; i += 2)',
    '    if (x >= spans[i] && x < spans[i + 1]) return true;', '  return false;', '}']
(ROOT / 'src/c/masks.h').write_text('\n'.join(output) + '\n')
print('Generated source-proportioned Arial masks at ' + ', '.join(map(str, SIZES)) + ' pixels.')
